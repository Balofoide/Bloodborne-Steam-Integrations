// Dev tool: turn tools/steam-classes.json + tools/steam-strings.json into frontend/steam/*.generated.ts
import fs from "node:fs"
const spec = JSON.parse(fs.readFileSync("tools/steam-classes.spec.json", "utf8"))
const mods = JSON.parse(fs.readFileSync("tools/steam-classes.json", "utf8"))
const strings = JSON.parse(fs.readFileSync("tools/steam-strings.json", "utf8"))
const head = (what) => `// Generated by tools/gen-frontend-data.mjs — ${what}\n// Source: Steam steamui (client build 11123049). Regenerate after a Steam update (see README).\n\n`
let m = head("Steam CSS-module lookups (keys) and hashes seen in that build (fallback).")
m += "export const MODULES = {\n"
for (const [k, keys] of Object.entries(spec)) m += `  ${k}: { keys: ${JSON.stringify(keys)}, fallback: ${JSON.stringify(mods[k] ?? {})} },\n`
m += "} as const\n\nexport type ModuleName = keyof typeof MODULES\n"
fs.mkdirSync("frontend/steam", { recursive: true })
fs.writeFileSync("frontend/steam/modules.generated.ts", m)
let s = head("Steam UI strings used as fallback when LocalizationManager is unavailable.")
s += `export const STRINGS = ${JSON.stringify({ pt: strings.brazilian, en: strings.english }, null, 1)} as const\n`
fs.writeFileSync("frontend/steam/strings.generated.ts", s)
console.log("modules:", Object.keys(mods).length, "strings:", Object.keys(strings.brazilian).length)
